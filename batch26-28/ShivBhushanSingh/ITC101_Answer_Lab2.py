        ax.set_xlim(-0.5, cols-0.5); ax.set_ylim(rows-0.5, -0.5); ax.set_aspect('equal')
        ax.set_xticks(range(cols)); ax.set_yticks(range(rows)); ax.grid(True, color='#dfe6e6')
