ROWS, COLS = 12, 18
walls = set()
for r in range(2, 9):  walls.add((r, 5))      # a wall with a gap at the bottom
for r in range(4, 12): walls.add((r, 10))     # another wall with a gap at the top
for c in range(10, 15): walls.add((3, c))     # a horizontal wall
